import { readFile, writeFile } from "node:fs/promises";
const root = new URL("../", import.meta.url);
let html = await readFile(new URL("dist/index.html", root), "utf8");
const script = html.match(/<script[^>]*src="([^"]+)"[^>]*><\/script>/);
const style = html.match(/<link[^>]*href="([^"]+\.css)"[^>]*>/);
if (!script || !style)
  throw new Error("Expected one Vite entry script and stylesheet");
const js = await readFile(
  new URL(`dist/${script[1].replace(/^\//, "")}`, root),
  "utf8",
);
const css = await readFile(
  new URL(`dist/${style[1].replace(/^\//, "")}`, root),
  "utf8",
);
html = html.replace(
  script[0],
  () =>
    `<script type="module">${js.replace(/<\/script/gi, "<\\/script")}</script>`,
);
html = html.replace(style[0], () => `<style>${css}</style>`);
html =
  "<!-- Generated by npm run build. Edit src/, not this portable build. -->\n" +
  html;
await writeFile(new URL("play.html", root), html);
console.log(
  `Portable game written to play.html (${Math.ceil(Buffer.byteLength(html) / 1024)} KB). Open directly in a browser; no server required.`,
);
