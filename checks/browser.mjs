import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
const browser=await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1440,height:1080}});let errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:5173');
await page.getByRole('heading',{name:'A little aim. A big impact.'}).waitFor();
await page.screenshot({path:'/tmp/battlefront-desktop.png',fullPage:true});
await page.getByRole('button',{name:'Blastoise',exact:true}).click();
await page.getByRole('button',{name:'Hydro Pump',exact:true}).click();
await page.locator('#angle').fill('10');
await page.locator('#fire').click();
await page.waitForFunction(()=>window.battlefront.state.phase==='summon');
await page.waitForTimeout(650);
await page.screenshot({path:'/tmp/battlefront-summon.png',fullPage:true});
await page.waitForFunction(()=>window.battlefront.state.turn===2,{},{timeout:15000});
assert.ok((await page.evaluate(()=>window.battlefront.state)).terrainVersion>0);
await page.getByRole('button',{name:'How to play'}).click();assert.equal(await page.locator('#modal').evaluate(e=>e.open),true);await page.getByRole('button',{name:'Let’s battle'}).click();
await page.locator('#restart').click();assert.equal((await page.evaluate(()=>window.battlefront.state)).turn,1);
await page.locator('canvas#game').click({position:{x:50,y:100}});await page.keyboard.down('KeyD');await page.waitForTimeout(200);await page.keyboard.up('KeyD');
await page.setViewportSize({width:720,height:950});await page.screenshot({path:'/tmp/battlefront-mobile.png',fullPage:true});
assert.deepEqual(errors,[]);console.log('Browser smoke passed: render, selection, summon, attack, terrain edit, next turn, help, restart; no page errors.');await browser.close();
